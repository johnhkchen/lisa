    #[test]
    fn an_edited_context_file_is_reported_to_init_and_never_to_doctor() {
        let dir = tempfile::tempdir().unwrap();
        fixture_0_4_4(dir.path());

        // A generated file with one line of Lisa's own prose replaced. It still
        // bears Lisa's preamble, so init has something to say `preserved` about.
        let edited = generated_claude_md().replace(
            "TODO: add a one-line project description here.",
            "A scheduler for climate model runs.",
        );
        fs::write(dir.path().join("CLAUDE.md"), &edited).unwrap();

        // Init names it, so the operator hears that Lisa looked and declined.
        let plan = crate::init::plan_init_actions(dir.path());
        let preserved = plan
            .iter()
            .filter(|action| {
                matches!(action, crate::init::InitAction::SafetySkip { path, .. }
                    if path == &dir.path().join("CLAUDE.md"))
            })
            .count();
        assert_eq!(preserved, 1, "init reports what it preserved: {plan:?}");

        // Doctor does not, and that is the point. Every doctor finding names a
        // command, and the command for a retired-and-preserved file removes it.
        // A prefix match is evidence enough to say "left alone" beside the file
        // it is about; it is not evidence enough to route somebody's own
        // writing toward `lisa clean`.
        assert!(find(&inventory(dir.path()), "CLAUDE.md").is_none());

        // And the file is untouched by the run itself.
        crate::init::run_init(dir.path(), false, crate::init::HistoryPreference::NoHistory)
            .unwrap();
        assert_eq!(
            fs::read_to_string(dir.path().join("CLAUDE.md")).unwrap(),
            edited
        );
    }

